const sourcePath = resolve("src/shared/config/design-tokens.tokens.json");
const outputPath = resolve("src/app/design-tokens.generated.css");
const source = JSON.parse(readFileSync(sourcePath, "utf8"));
const tokens = [];

function visit(group, path = []) {
  for (const [name, value] of Object.entries(group)) {
    if (name.startsWith("$")) continue;
    const nextPath = [...path, name];
    if (value && typeof value === "object" && "$value" in value) {
      tokens.push({ path: nextPath, token: value });
    } else if (value && typeof value === "object") {
      visit(value, nextPath);
    }
  }
}

visit(source);

const cssName = (path) => `--${path.join("-")}`;
const resolveValue = (value) => {
  if (typeof value !== "string") {
    if (Array.isArray(value)) {
      return typeof value[0] === "number"
        ? `cubic-bezier(${value.join(", ")})`
        : value.join(", ");
    }
    return String(value);
  }
  const alias = value.match(/^\{(.+)\}$/);
  return alias ? `var(--${alias[1].replaceAll(".", "-")})` : value;
};

const reference = tokens.filter(({ path }) => path[0] === "reference");
const semantic = tokens.filter(({ path }) => path[0] === "semantic");
const product = tokens.filter(({ path }) => path[0] === "product");
const component = tokens.filter(({ path }) => path[0] === "component");

const declarations = (items, mode = null) =>
  items
    .map(({ path, token }) => {
      const value = mode ? token.$extensions?.mode?.[mode] : token.$value;
      if (value === undefined) return null;
      return `  ${cssName(path)}: ${resolveValue(value)};`;
    })
    .filter(Boolean)
    .join("\n");

